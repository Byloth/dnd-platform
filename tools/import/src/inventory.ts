const HEADER = "<!-- Generated by tools/import/src/inventory.ts from the datasets pinned in tools/import/sources.lock.yaml. Do not edit. -->\n\n";

function write(name: string, body: string): void
{
    writeFileSync(resolve(OUT, name), `${HEADER}${body.trimEnd()}\n`);
}
function md(text: string | null | undefined): string
{
    return (text ?? "").replace(/\r\n/g, "\n").trim();
}
function cell(text: string | null | undefined): string
{
    return md(text).replace(/\|/g, "\\|")
        .replace(/\n+/g, " ");
}
function by<T>(items: T[], key: (item: T) => string): Map<string, T[]>
{
    const map = new Map<string, T[]>();
    for (const item of items)
    {
        const k = key(item);
        map.set(k, [...(map.get(k) ?? []), item]);
    }

    return map;
}
function count<T>(items: T[], key: (item: T) => string): [string, number][]
{
    return [...by(items, key).entries()]
        .map(([k, v]) => [k, v.length] as [string, number])
        .sort((a, b) => a[0].localeCompare(b[0]));
}

// ---- 5e-database (counts and structured tables) ----------------------------

const DB = "src/2014/en/5e-SRD-";
function db<T>(name: string): T[] { return readCachedJson<T[]>("5e-database", `${DB}${name}.json`); }
interface DbLevel
{
    level: number;
    prof_bonus: number;
    class: { index: string };
    subclass?: { index: string };
    class_specific?: Record<string, unknown>;
    spellcasting?: Record<string, number>;
}
interface DbMagicItem
{
    index: string;
    name: string;
    rarity: { name: string };
    variant: boolean;
    variants: unknown[];
    desc: string[];
    equipment_category: { index: string };
}
const dbCounts: Record<string, number> = {};
for (const file of readdirSync(resolve(REPO_ROOT, "tools/import/cache/5e-database/src/2014/en")))
{
    const name = file.replace(/^5e-SRD-|\.json$/g, "");
    dbCounts[name] = db<unknown>(name).length;
}
const dbLevels = db<DbLevel>("Levels");
const dbMagic = db<DbMagicItem>("Magic-Items");

// ---- Open5e (primary) ------------------------------------------------------

const classes = o5e.rows<o5e.CharacterClass>("CharacterClass");
const features = o5e.rows<o5e.ClassFeature>("ClassFeature");
const featureItems = o5e.rows<o5e.ClassFeatureItem>("ClassFeatureItem");
const species = o5e.rows<o5e.Species>("Species");
const traits = o5e.rows<o5e.SpeciesTrait>("SpeciesTrait");
const backgrounds = o5e.rows<o5e.Background>("Background");
const backgroundBenefits = o5e.rows<o5e.BackgroundBenefit>("BackgroundBenefit");
const feats = o5e.rows<o5e.Feat>("Feat");
const featBenefits = o5e.rows<o5e.FeatBenefit>("FeatBenefit");
const spells = o5e.rows<o5e.Spell>("Spell");
const spellOptions = o5e.rows<o5e.SpellCastingOption>("SpellCastingOption");
const items = o5e.rows<o5e.Item>("Item");
const magicItems = o5e.rows<o5e.Item>("MagicItem");
const weapons = o5e.rows<o5e.Weapon>("Weapon");
const weaponProps = o5e.rows<o5e.WeaponPropertyAssignment>("WeaponPropertyAssignment");
const armors = o5e.rows<o5e.Armor>("Armor");
const conditions = o5e.rows<o5e.ConditionDescription>("ConditionDescription");
const rules = o5e.rows<o5e.Rule>("Rule");
const ruleSets = o5e.rows<o5e.RuleSet>("RuleSet");

const baseClasses = classes
    .filter((c) => c.fields.subclass_of === null)
    .sort((a, b) => a.fields.name.localeCompare(b.fields.name));
const subclasses = classes.filter((c) => c.fields.subclass_of !== null);
const itemsByFeature = by(featureItems, (i) => i.fields.parent);
const featuresByOwner = by(features, (f) => f.fields.parent);
const traitsByOwner = by(traits, (t) => t.fields.parent);
const optionsBySpell = by(spellOptions, (s) => s.fields.parent);
const propsByWeapon = by(weaponProps, (p) => p.fields.weapon);
const weaponByPk = new Map(weapons.map((w) => [String(w.pk), w.fields]));
const armorByPk = new Map(armors.map((a) => [String(a.pk), a.fields]));

function featureLevel(pk: string | number): number | null
{
    const levels = (itemsByFeature.get(String(pk)) ?? []).map((i) => i.fields.level);

    return levels.length ? Math.min(...levels) : null;
}
function featureTable(pk: string | number): string
{
    const rowsWithValue = (itemsByFeature.get(String(pk)) ?? [])
        .filter((i) => i.fields.column_value !== null || i.fields.detail !== null)
        .sort((a, b) => a.fields.level - b.fields.level);
    if (!rowsWithValue.length) { return ""; }

    return `  Table: ${rowsWithValue.map((i) => `${i.fields.level} → ${i.fields.column_value ?? i.fields.detail}`).join("; ")}\n`;
}

