// ---- classes / subclasses ----------------------------------------------------

function classSection(c: { pk: string | number, fields: o5e.CharacterClass }): string[]
{
    const id = o5e.slug(c.pk);
    const lines: string[] = [`## ${c.fields.name} (\`${id}\`)`, ""];
    if (c.fields.subclass_of === null)
    {
        lines.push(`- Hit die: ${c.fields.hit_dice}; saving throws: ${c.fields.saving_throws.join(", ")}; caster type: ${c.fields.caster_type ?? "none"}`);
        const levels = dbLevels.filter((l) => l.class.index === id && !l.subclass).sort((a, b) => a.level - b.level);
        const specific = levels.find((l) => l.class_specific)?.class_specific ?? {};
        const columns = Object.keys(specific);
        if (columns.length)
        {
            lines.push("", "### Level table (5e-database `class_specific`)", "", `| Level | Prof | ${columns.join(" | ")} |`, `|---|---|${columns.map(() => "---").join("|")}|`);
            for (const l of levels)
            {
                lines.push(`| ${l.level} | +${l.prof_bonus} | ${columns.map((k) => JSON.stringify(l.class_specific?.[k] ?? "")).join(" | ")} |`);
            }
        }
        const slots = levels.find((l) => l.spellcasting)?.spellcasting;
        if (slots)
        {
            const keys = Object.keys(slots);
            lines.push("", "### Spellcasting table (5e-database)", "", `| Level | ${keys.join(" | ")} |`, `|---|${keys.map(() => "---").join("|")}|`);
            for (const l of levels) { lines.push(`| ${l.level} | ${keys.map((k) => l.spellcasting?.[k] ?? "").join(" | ")} |`); }
        }
    }
    else
    {
        lines.push(`- Subclass of \`${o5e.slug(c.fields.subclass_of)}\``);
    }
    const own = (featuresByOwner.get(String(c.pk)) ?? [])
        .map((f) => ({ f: f, level: featureLevel(f.pk) }))
        .sort((a, b) => (a.level ?? 99) - (b.level ?? 99) || a.f.fields.name.localeCompare(b.f.fields.name));
    lines.push("", `### Features (${own.length})`, "");
    for (const { f, level } of own)
    {
        lines.push(`#### ${f.fields.name} — level ${level ?? "?"} (\`${o5e.slug(f.pk)}\`)`, "", featureTable(f.pk), md(f.fields.desc), "");
    }

    return lines;
}
write("classes.md", ["# Classes", "", ...baseClasses.flatMap(classSection)].join("\n"));
write("subclasses.md", ["# Subclasses", "", ...subclasses.sort((a, b) => a.fields.name.localeCompare(b.fields.name)).flatMap(classSection)].join("\n"));

