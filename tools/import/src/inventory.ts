write("backgrounds.md", ["# Backgrounds", "", ...backgroundLines].join("\n"));

const featLines = feats.flatMap((f) => [
    `## ${f.fields.name} (\`${o5e.slug(f.pk)}\`)`, "", `Prerequisite: ${f.fields.prerequisite ?? "none"}`, "", md(f.fields.desc), "",
    ...featBenefits
        .filter((x) => x.fields.parent === f.pk)
        .flatMap((x, i) => [`### Benefit ${i + 1}`, "", md(x.fields.desc), ""])
]);
write("feats.md", ["# Feats", "", ...featLines].join("\n"));
const conditionLines = conditions.flatMap((c) => [`## ${c.fields.describes}`, "", md(c.fields.desc), ""]);
write("conditions.md", ["# Conditions", "", ...conditionLines].join("\n"));

const rulesByRuleSet = by(rules, (r) => r.fields.ruleset);
const ruleLines = ruleSets
    .sort((a, b) => a.fields.name.localeCompare(b.fields.name))
    .flatMap((rs) =>
    {
        const own = (rulesByRuleSet.get(String(rs.pk)) ?? []).sort((a, b) => a.fields.index - b.fields.index);
        const bullets = own.map((r) => `- ${r.fields.name} (\`${o5e.slug(r.pk)}\`, ${md(r.fields.desc).length} chars)`);

        return [`## ${rs.fields.name} (\`${o5e.slug(rs.pk)}\`)`, "", ...bullets, ""];
    });
write("rules.md", ["# Rules", "", "Reference text available for the assistant and the cheat sheet (`Rule` entities).", "", ...ruleLines].join("\n"));

// ---- spells ------------------------------------------------------------------

{
    const lines: string[] = ["# Spells", "", "Metadata from Open5e; casting options list the upcast and ritual rows available upstream.", ""];
    for (const [level, group] of [...by(spells, (s) => String(s.fields.level)).entries()].sort())
    {
        lines.push(`## Level ${level} (${group.length})`, "");
        for (const s of group.sort((a, b) => a.fields.name.localeCompare(b.fields.name)))
        {
            const f = s.fields;
            const comps = [f.verbal && "V", f.somatic && "S", f.material && `M${f.material_specified ? ` (${f.material_specified})` : ""}`].filter(Boolean).join(", ");
            const opts = (optionsBySpell.get(String(s.pk)) ?? []).map((x) => x.fields.type).filter((t) => t !== "default");
            lines.push(`### ${f.name} (\`${o5e.slug(s.pk)}\`)`, "",
                `- ${f.school}; casting time: ${f.casting_time}${f.reaction_condition ? ` (${f.reaction_condition})` : ""}; range: ${f.range_text}; duration: ${f.duration}${f.concentration ? " (concentration)" : ""}${f.ritual ? "; ritual" : ""}`,
                `- components: ${comps}; classes: ${f.classes.map(o5e.slug).join(", ")}`,
                `- structured: attack=${f.attack_roll}, save=${f.saving_throw_ability ?? "-"}, damage=${f.damage_roll ?? "-"} ${f.damage_types.join("/")}, shape=${f.shape_type ?? "-"}${f.shape_size ? ` ${f.shape_size}` : ""}, targets=${f.target_type ?? "-"}${f.target_count ? ` ×${f.target_count}` : ""}; options: ${opts.length ? opts.join(", ") : "none"}`,
                "", md(f.desc), ...(md(f.higher_level) ? ["", `*At higher levels.* ${md(f.higher_level)}`] : []), "");
        }
    }
    write("spells.md", lines.join("\n"));
}

// ---- items -------------------------------------------------------------------

{
    const lines: string[] = ["# Items", "", "## Weapons", "", "| Name | Simple | Damage | Range | Properties |", "|---|---|---|---|---|"];
    for (const w of weapons.sort((a, b) => a.fields.name.localeCompare(b.fields.name)))
    {
        const props = (propsByWeapon.get(String(w.pk)) ?? []).map((p) => `${o5e.slug(p.fields.property)}${p.fields.detail ? ` (${p.fields.detail})` : ""}`).join(", ");
        lines.push(`| ${w.fields.name} | ${w.fields.is_simple} | ${w.fields.damage_dice} ${w.fields.damage_type} | ${w.fields.range}/${w.fields.long_range} | ${props} |`);
    }
    lines.push("", "## Armour", "", "| Name | Base AC | + DEX | DEX cap | Stealth disadvantage | STR required |", "|---|---|---|---|---|---|");
    for (const a of armors.sort((x, y) => x.fields.name.localeCompare(y.fields.name)))
    {
        lines.push(`| ${a.fields.name} | ${a.fields.ac_base} | ${a.fields.ac_add_dexmod} | ${a.fields.ac_cap_dexmod ?? "-"} | ${a.fields.grants_stealth_disadvantage} | ${a.fields.strength_score_required ?? "-"} |`);
    }
    lines.push("", "## Mundane items by category", "");
    for (const [cat, group] of [...by(items, (i) => i.fields.category).entries()].sort())
    {
        lines.push(`### ${cat} (${group.length})`, "", "| Name | Cost | Weight | Description |", "|---|---|---|---|");
        for (const i of group.sort((a, b) => a.fields.name.localeCompare(b.fields.name)))
        {
            lines.push(`| ${i.fields.name} | ${i.fields.cost ?? "-"} | ${i.fields.weight ?? "-"} | ${cell(i.fields.desc).slice(0, 200)} |`);
        }
        lines.push("");
    }
    lines.push("## Magic items (5e-database base entries, variants collapsed)", "", "| Name | Category | Rarity | Variants | Description |", "|---|---|---|---|---|");
    for (const m of dbMagic.filter((x) => !x.variant).sort((a, b) => a.name.localeCompare(b.name)))
    {
        lines.push(`| ${m.name} | ${m.equipment_category.index} | ${m.rarity.name} | ${m.variants.length} | ${cell(m.desc.join(" ")).slice(0, 300)} |`);
    }
    write("items.md", lines.join("\n"));
    void weaponByPk;
    void armorByPk;
}

// ---- classification skeletons ------------------------------------------------

interface FeatureRecord
{
    id: string;
    owner: string;
    ownerType: "class" | "subclass" | "species" | "subspecies" | "background" | "feat";
    level: number | null;
    name: string;
    table?: string;
    text: string;
    mechanics: null;
}
const records: FeatureRecord[] = [];
for (const c of classes)
{
    const kind = c.fields.subclass_of === null ? "class" : "subclass";
    for (const f of featuresByOwner.get(String(c.pk)) ?? [])
    {
        const table = featureTable(f.pk).replace(/^\s*Table: /, "")
            .trim();
        records.push({
            id: `srd51.feature.${o5e.slug(c.pk)}.${o5e.slug(f.pk).replace(`${o5e.slug(c.pk)}_`, "")}`,
            owner: o5e.slug(c.pk),
            ownerType: kind,
            level: featureLevel(f.pk),
            name: f.fields.name,
            ...(table ? { table } : {}),
            text: md(f.fields.desc),
            mechanics: null
        });
    }
}
for (const s of species)
{
    const kind = s.fields.subspecies_of === null ? "species" : "subspecies";
    for (const t of traitsByOwner.get(String(s.pk)) ?? [])
    {
        records.push({
            id: `srd51.feature.${o5e.slug(s.pk)}.${o5e.slug(t.pk).replace(`${o5e.slug(s.pk)}_`, "")}`,
            owner: o5e.slug(s.pk),
            ownerType: kind,
            level: null,
            name: t.fields.name,
            text: md(t.fields.desc),
            mechanics: null
        });
    }
}
for (const b of backgroundBenefits)
{
    records.push({
        id: `srd51.feature.${o5e.slug(b.fields.parent)}.${o5e.slug(b.pk).replace(`${o5e.slug(b.fields.parent)}_`, "")}`,
        owner: o5e.slug(b.fields.parent),
        ownerType: "background",
        level: null,
        name: `${b.fields.name} (${b.fields.type})`,
        text: md(b.fields.desc),
        mechanics: null
    });
}
for (const f of feats)
{
    const benefits = featBenefits.filter((x) => x.fields.parent === f.pk).map((x) => `- ${md(x.fields.desc)}`)
        .join("\n");
    records.push({
        id: `srd51.feature.feat.${o5e.slug(f.pk)}`,
        owner: o5e.slug(f.pk),
        ownerType: "feat",
        level: null,
        name: f.fields.name,
        text: `Prerequisite: ${f.fields.prerequisite ?? "none"}\n${md(f.fields.desc)}\n${benefits}`,
        mechanics: null
    });
}
writeFileSync(resolve(OUT, "features.yaml"), "# Classification skeleton: one record per feature, trait or benefit. Generated; " +
`the classified copy is classification.yaml.\n${stringify({ records }, { lineWidth: 0 })}`);

const spellRecords = spells
    .sort((a, b) => a.fields.level - b.fields.level || a.fields.name.localeCompare(b.fields.name))
    .map((s) => ({
        id: `srd51.spell.${o5e.slug(s.pk)}`,
        name: s.fields.name,
        level: s.fields.level,
        school: s.fields.school,
        castingTime: s.fields.casting_time,
        duration: s.fields.duration,
        concentration: s.fields.concentration,
        ritual: s.fields.ritual,
        attack: s.fields.attack_roll,
        save: s.fields.saving_throw_ability,
        damage: s.fields.damage_roll,
        shape: s.fields.shape_type,
        text: md(s.fields.desc),
        higherLevel: md(s.fields.higher_level) || null,
        mechanics: null
    }));
writeFileSync(resolve(OUT, "spells-classification.yaml"), `# Classification skeleton for spells (reduced vocabulary). Generated.\n${stringify({ records: spellRecords }, { lineWidth: 0 })}`);

const magicRecords = dbMagic.filter((m) => !m.variant).sort((a, b) => a.name.localeCompare(b.name))
    .map((m) => ({
        id: `srd51.item.${m.index}`,
        name: m.name,
        category: m.equipment_category.index,
        rarity: m.rarity.name,
        variants: m.variants.length,
        text: m.desc.join("\n"),
        mechanics: null
    }));
writeFileSync(resolve(OUT, "magic-items-classification.yaml"), `# Classification skeleton for magic items (reduced vocabulary). Generated.\n${stringify({ records: magicRecords }, { lineWidth: 0 })}`);

// ---- work partitions for the classification agents ---------------------------

const PARTS: Record<string, (r: FeatureRecord) => boolean> = {
    "part-1-classes-a-d": (r) => ["barbarian", "path-of-the-berserker", "bard", "college-of-lore", "cleric", "life-domain", "druid", "circle-of-the-land"].includes(r.owner),
    "part-2-classes-f-r": (r) => ["fighter", "champion", "monk", "way-of-the-open-hand", "paladin", "oath-of-devotion", "ranger", "hunter"].includes(r.owner),
    "part-3-classes-r-w": (r) => ["rogue", "thief", "sorcerer", "draconic-bloodline", "warlock", "the-fiend", "wizard", "school-of-evocation"].includes(r.owner),
    "part-4-species-bg-feat": (r) => ["species", "subspecies", "background", "feat"].includes(r.ownerType)
};
let assigned = 0;
for (const [name, filter] of Object.entries(PARTS))
{
    const part = records.filter(filter);
    assigned += part.length;
    writeFileSync(resolve(WORK, `${name}.yaml`), stringify({ records: part }, { lineWidth: 0 }));
}
